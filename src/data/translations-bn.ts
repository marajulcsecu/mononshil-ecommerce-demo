export function getLocalizedCategory(category: Category, locale: Locale): Category {
  if (locale === "en") return category;
  const tr = CATEGORY_BN[category.slug];
  return {
    ...category,
    name: tr.name,
    shortTitle: tr.shortTitle,
    tagline: tr.tagline,
    description: tr.description,
  };
}

export function getLocalizedProduct(product: Product, locale: Locale): Product {
  if (locale === "en") return product;
  const tr = PRODUCT_BN[product.slug];
  if (!tr) return product;
  return {
    ...product,
    name: tr.name,
    shortDescription: tr.shortDescription,
    description: tr.description,
    sizeLabel: tr.sizeLabel ?? product.sizeLabel,
    highlights: tr.highlights,
    specs: tr.specs,
  };
}

export function translateBadge(badge: ProductBadge, locale: Locale): string {
  return locale === "bn" ? BADGE_BN[badge] : badge;
}

export function translateColorName(name: string, locale: Locale): string {
  return locale === "bn" ? COLOR_BN[name] ?? name : name;
}

export function translatePackLabel(label: string, locale: Locale): string {
  return locale === "bn" ? PACK_BN[label] ?? label : label;
}

export function translateSizeValue(size: string, locale: Locale): string {
  return locale === "bn" ? toBanglaDigits(size) : size;
}
