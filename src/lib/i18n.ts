import type { Locale } from "@/types/i18n";

const BANGLA_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function toBanglaDigits(input: string | number): string {
  return String(input).replace(/\d/g, (digit) => BANGLA_DIGITS[Number(digit)] ?? digit);
}

export function formatNumber(value: number, locale: Locale): string {
  const formatted = value.toLocaleString("en-US");
  return locale === "bn" ? toBanglaDigits(formatted) : formatted;
}

export function formatRating(value: number, locale: Locale): string {
  const fixed = value.toFixed(1);
  return locale === "bn" ? toBanglaDigits(fixed) : fixed;
}

export function formatPrice(amount: number, locale: Locale): string {
  const safe = Math.max(0, Math.round(amount));
  const formatted = safe.toLocaleString("en-US");
  return locale === "bn" ? `৳ ${toBanglaDigits(formatted)}` : `Tk ${formatted}`;
}

